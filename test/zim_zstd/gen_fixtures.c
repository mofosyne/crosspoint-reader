// Generates ZstdFixtures.h. Not part of the build; run by hand when fixtures must change:
//   cc -o gen gen_fixtures.c -lzstd && ./gen > ZstdFixtures.h
// Needs system libzstd only here: the tests themselves use the vendored decoder.
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <zstd.h>

// Must match fixtureText() in ZstdClusterDecoderTest.cpp.
static void fixtureText(uint8_t* out, size_t n) {
  static const char* words[] = {"apple", "tree", "river", "stone", "light", "the", "of", "and", "paris", "moon"};
  uint32_t s = 12345;
  size_t pos = 0;
  while (pos < n) {
    s = s * 1103515245u + 12345u;
    const char* w = words[(s >> 16) % 10];
    for (; *w && pos < n; ++w) out[pos++] = (uint8_t)*w;
    if (pos < n) out[pos++] = ' ';
  }
}

static void emit(const char* name, const uint8_t* d, size_t n) {
  printf("inline constexpr uint8_t %s[] = {", name);
  for (size_t i = 0; i < n; ++i) printf("%s%u,", i % 16 == 0 ? "\n    " : " ", d[i]);
  printf("\n};\n\n");
}

int main(void) {
  const size_t streamedSize = 48000, knownSize = 4096;
  uint8_t* text = malloc(streamedSize);
  fixtureText(text, streamedSize);

  // Streamed without a pledged size: the frame header has no content size, like Kiwix.
  size_t cap = ZSTD_compressBound(streamedSize);
  uint8_t* out = malloc(cap);
  ZSTD_CCtx* cctx = ZSTD_createCCtx();
  ZSTD_CCtx_setParameter(cctx, ZSTD_c_compressionLevel, 3);
  // A single ZSTD_e_end call with all the input would record the size in the header, so feed
  // the first half with ZSTD_e_continue: the frame then has no content size, like Kiwix.
  ZSTD_outBuffer ob = {out, cap, 0};
  ZSTD_inBuffer first = {text, streamedSize / 2, 0};
  while (first.pos < first.size) ZSTD_compressStream2(cctx, &ob, &first, ZSTD_e_continue);
  ZSTD_inBuffer rest = {text + streamedSize / 2, streamedSize - streamedSize / 2, 0};
  size_t rem;
  do {
    rem = ZSTD_compressStream2(cctx, &ob, &rest, ZSTD_e_end);
  } while (rem != 0);
  printf("// clang-format off\n// Generated by gen_fixtures.c with libzstd %s. Do not edit.\n#pragma once\n\n#include <stddef.h>\n#include <stdint.h>\n\n",
         ZSTD_versionString());
  printf("inline constexpr size_t STREAMED_PLAIN_SIZE = %zu;\n", streamedSize);
  printf("inline constexpr size_t KNOWN_PLAIN_SIZE = %zu;\n\n", knownSize);
  emit("STREAMED_FRAME", out, ob.pos);

  size_t n2 = ZSTD_compress(out, cap, text, knownSize, 3);
  emit("KNOWN_FRAME", out, n2);
  return 0;
}
